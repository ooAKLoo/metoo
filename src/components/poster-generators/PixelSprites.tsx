// ---------------------------------------------------------------------------
// PixelSpriteSVG
// ---------------------------------------------------------------------------

interface PixelSpriteSVGProps {
  spriteName: string;
  size?: number;
  color?: string;
}

export const PixelSpriteSVG = React.memo<PixelSpriteSVGProps>(
  ({ spriteName, size = 32, color = "#1a1a2e" }) => {
    const data = SPRITE_DATA[spriteName];
    if (!data) return null;

    const rects: React.ReactNode[] = [];
    for (let row = 0; row < 16; row++) {
      for (let col = 0; col < 16; col++) {
        if (data[row][col] === 1) {
          rects.push(
            <rect
              key={`${row}-${col}`}
              x={col}
              y={row}
              width={1}
              height={1}
              fill={color}
            />
          );
        }
      }
    }

    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 16 16"
        xmlns="http://www.w3.org/2000/svg"
        style={{ imageRendering: "pixelated" }}
      >
        {rects}
      </svg>
    );
  }
);

PixelSpriteSVG.displayName = "PixelSpriteSVG";

// ---------------------------------------------------------------------------
// Seeded RNG helper
// ---------------------------------------------------------------------------

function mkRng(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 16807 + 0) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

// ---------------------------------------------------------------------------
// generatePixelScene
// ---------------------------------------------------------------------------

export function generatePixelScene(
  seed: number,
  count: number
): PixelSceneItem[] {
  const rng = mkRng(seed);
  const items: PixelSceneItem[] = [];

  for (let i = 0; i < count; i++) {
    const y = 10 + rng() * 80; // 10-90%
    const x = 5 + rng() * 90; // 5-95%
    // Scale based on y for depth effect: items closer to bottom are larger
    const scale = 0.4 + (y / 100) * 0.8;
    const spriteIndex = Math.floor(rng() * SPRITE_NAMES.length);
    const spriteName = SPRITE_NAMES[spriteIndex];
    const itemSeed = Math.floor(rng() * 100000);

    items.push({ x, y, scale, spriteName, seed: itemSeed });
  }

  // Sort by y for depth ordering (items further back rendered first)
  items.sort((a, b) => a.y - b.y);

  return items;
}
